/**
 * Set this repo's git identity to the OWNER, not the agent.
 *
 * Why this exists: every agent that has touched this repo — Claude Code,
 * Cowork, Cursor, the drain bot — committed with its own name in the git
 * AUTHOR field. That field is what GitHub credits, what the contribution graph
 * counts, and what `git blame` reports, so the owner was steadily losing
 * attribution on his own repository to whichever tool happened to type.
 *
 * Author and committer are separate on purpose. A harness that needs a
 * particular COMMITTER (for a signature or a Verified badge) can still have
 * one; it has no reason to claim the author.
 *
 * Idempotent, local to this clone (never --global), and safe to run from a
 * SessionStart hook on every session.
 *
 * Usage: npm run git:identity
 */
import { execSync } from "node:child_process"

const OWNER_NAME = "Ranvir Thind"
// GitHub's contribution graph matches the RAW commit author email to an
// account and ignores .mailmap entirely, so this has to be an address verified
// on the owner's GitHub account or the credit does not land. The
// <id>+<user>@users.noreply.github.com form is generated by GitHub itself and
// is always linked — it is already the author of the commits the owner made by
// hand in this repo. Swap in a personal address only after verifying it at
// https://github.com/settings/emails.
const OWNER_EMAIL = "130034150+ranvir01@users.noreply.github.com"

const git = (args) => execSync(`git ${args}`, { encoding: "utf-8" }).trim()
const tryGit = (args) => {
  try {
    return git(args)
  } catch {
    return ""
  }
}

// Not a git work tree (tarball, some CI checkouts) — nothing to do, don't fail.
if (!tryGit("rev-parse --is-inside-work-tree")) {
  console.log("git-identity: not a git work tree, skipping.")
  process.exit(0)
}

const before = `${tryGit("config user.name")} <${tryGit("config user.email")}>`
git(`config user.name "${OWNER_NAME}"`)
git(`config user.email "${OWNER_EMAIL}"`)
const after = `${git("config user.name")} <${git("config user.email")}>`

if (before === after) {
  console.log(`git-identity: already ${after}`)
} else {
  console.log(`git-identity: ${before} → ${after}`)
  console.log("   Commits from this clone now credit the owner as author.")
}
